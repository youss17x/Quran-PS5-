#!/usr/bin/env python3
"""Generate Quran PS5 data tables and pre-rendered Arabic UI labels.

Arabic needs shaping (joined letters, right-to-left), which the console build does not do.
So every Arabic string the app shows is rendered here, at build time, into a PNG
(Pillow + libraqm + the Amiri font), and the app only draws images.

Inputs (data/):  suras.json, pages/page_N.json (Madani 604-page layout, from rayed/Quran),
                 Amiri-Bold.ttf / Amiri-Regular.ttf (SIL OFL)
Outputs:         src/quran_data.h, assets/ui/*.png
"""
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent.parent
data = root / 'data'
out_ui = root / 'assets' / 'ui'
out_ui.mkdir(parents=True, exist_ok=True)

# ---------------- tables ----------------
suras = json.load(open(data / 'suras.json', encoding='utf-8'))
assert len(suras) == 114
fix = {5: 'المائدة', 20: 'طه', 82: 'الانفطار', 84: 'الانشقاق', 85: 'البروج', 98: 'البينة'}
names = [fix.get(s['id'], s['name']) for s in suras]
ayahs = [s['ayas'] for s in suras]
sura_page = [s['page'] for s in suras]
assert sum(ayahs) == 6236

page_first = []
for p in range(1, 605):
    entries = json.load(open(data / 'pages' / f'page_{p}.json'))
    e = min(entries, key=lambda x: (x['sura_id'], x['aya_id']))
    page_first.append((e['sura_id'], e['aya_id']))
assert page_first[0] == (1, 1) and page_first[21] == (2, 142)
assert all(page_first[i] < page_first[i + 1] for i in range(603))
for i, sp in enumerate(sura_page):                       # cross-check the two sources
    assert page_first[sp - 1] <= (i + 1, 1), (i + 1, sp)

# Start page of each juz in the Madani mushaf
juz_page = [1, 22, 42, 62, 82, 102, 121, 142, 162, 182, 201, 222, 242, 262, 282,
            302, 322, 342, 362, 382, 402, 422, 442, 462, 482, 502, 522, 542, 562, 582]

# Reciters on everyayah.com (per-ayah MP3: data/<folder>/SSSAAA.mp3)
reciters = [
    ('Alafasy_128kbps', 'مشاري راشد العفاسي'),
    ('Husary_64kbps', 'محمود خليل الحصري'),
    ('Minshawy_Murattal_128kbps', 'محمد صديق المنشاوي'),
    ('Abdul_Basit_Murattal_64kbps', 'عبد الباسط عبد الصمد'),
    ('Abdurrahmaan_As-Sudais_192kbps', 'عبد الرحمن السديس'),
    ('Saood_ash-Shuraym_128kbps', 'سعود الشريم'),
    ('Abu_Bakr_Ash-Shaatree_128kbps', 'أبو بكر الشاطري'),
    ('Hani_Rifai_192kbps', 'هاني الرفاعي'),
]

h = ['/* Generated by tools/gen_data.py - do not edit. */', '#pragma once', '',
     f'#define SURA_COUNT 114', f'#define JUZ_COUNT 30', f'#define RECITER_COUNT {len(reciters)}', '',
     'static const unsigned short SURA_AYAHS[114] = {' + ','.join(map(str, ayahs)) + '};',
     'static const unsigned short SURA_PAGE[114] = {' + ','.join(map(str, sura_page)) + '};',
     'static const unsigned short JUZ_PAGE[30] = {' + ','.join(map(str, juz_page)) + '};',
     '/* first ayah on each page: PAGE_FIRST[p-1] = {sura, ayah} */',
     'static const unsigned short PAGE_FIRST[604][2] = {' + ','.join(f'{{{s},{a}}}' for s, a in page_first) + '};',
     'static const char *const RECITER_FOLDER[' + str(len(reciters)) + '] = {' + ','.join(f'"{f}"' for f, _ in reciters) + '};',
     '']
(root / 'src' / 'quran_data.h').write_text('\n'.join(h), encoding='utf-8')

# ---------------- labels ----------------
BOLD = str(data / 'Amiri-Bold.ttf')
REG = str(data / 'Amiri-Regular.ttf')
SYM = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
RAQM = ImageFont.Layout.RAQM


def font(path, size):
    return ImageFont.truetype(path, size, layout_engine=RAQM)


def runs_image(runs, pad=6):
    """runs: list of (text, path, size) laid out right-to-left (first run is rightmost)."""
    parts = []
    for text, path, size in runs:
        f = font(path, size)
        rtl = path != SYM
        kw = dict(direction='rtl', language='ar') if rtl else {}
        bb = f.getbbox(text, **kw)
        asc, desc = f.getmetrics()
        w = bb[2] - bb[0] + 2
        im = Image.new('L', (max(w, 1), asc + desc + 2 * pad), 0)
        ImageDraw.Draw(im).text((-bb[0] + 1, pad), text, font=f, fill=255, **kw)
        parts.append((im, asc))
    base = max(a for _, a in parts)
    H = max(im.height - a + base for im, a in parts)
    W = sum(im.width for im, _ in parts)
    out = Image.new('L', (W, H), 0)
    x = W
    for im, a in parts:
        x -= im.width
        out.paste(im, (x, base - a))
    bbox = out.getbbox() or (0, 0, 1, 1)
    out = out.crop((max(bbox[0] - pad, 0), max(bbox[1] - pad, 0),
                    min(bbox[2] + pad, out.width), min(bbox[3] + pad, out.height)))
    rgba = Image.new('RGBA', out.size, (255, 255, 255, 0))
    rgba.putalpha(out)
    return rgba


def text_image(text, path=BOLD, size=64):
    return runs_image([(text, path, size)])


def save(name, im):
    im.save(out_ui / f'{name}.png', optimize=True)


for i, n in enumerate(names, 1):
    save(f'sura_{i:03d}', text_image('سورة ' + n, BOLD, 64))
for d in range(10):                                        # Arabic-Indic digits, composed left-to-right
    save(f'digit_{d}', text_image(chr(0x0660 + d), BOLD, 64))
for i, (_, n) in enumerate(reciters):
    save(f'reciter_{i}', text_image(n, BOLD, 64))

words = {
    'w_index': 'الفهرس', 'w_suras': 'السور', 'w_juz_tab': 'الأجزاء', 'w_juz': 'الجزء',
    'w_page': 'صفحة', 'w_reciter': 'القارئ', 'w_playing': 'تلاوة', 'w_paused': 'متوقفة مؤقتًا',
    'w_loading': 'جارٍ تحميل التلاوة', 'w_audio_err': 'تعذّر تحميل التلاوة، تحقق من الإنترنت',
    'w_ayah': 'آية',
}
for k, v in words.items():
    save(k, text_image(v, BOLD, 64))

S = 58
save('hint_main', runs_image([
    ('△', SYM, S), (' الفهرس    ', BOLD, S), ('□', SYM, S), (' تلاوة    ', BOLD, S),
    ('○', SYM, S), (' القارئ    ', BOLD, S), ('L1 R1', SYM, S - 10), (' تقليب', BOLD, S)]))
save('hint_index', runs_image([
    ('✕', SYM, S), (' فتح    ', BOLD, S), ('○', SYM, S), (' رجوع    ', BOLD, S),
    ('◀ ▶', SYM, S - 6), (' السور / الأجزاء', BOLD, S)]))
save('hint_reciter', runs_image([
    ('▲ ▼', SYM, S - 6), (' اختيار    ', BOLD, S), ('✕', SYM, S), (' تأكيد    ', BOLD, S),
    ('○', SYM, S), (' رجوع', BOLD, S)]))
print('generated', len(list(out_ui.glob('*.png'))), 'labels; pages ok')
