#!/usr/bin/env python3
"""Locate the 15-line text block on each mushaf image (zeyadetman/quran-pages-images, 974x1403)
and combine it with the ayah segments of rayed/Quran (290-wide, 15 lines) into src/quran_layout.h.

Line slots: a uniform 15-line grid fitted to the ink profile (about 77.5 px per line).
Columns:    inner edges of the green ornamental frame.
Pages 1-2 use a decorative layout and are left without highlight."""
import json, sys
from pathlib import Path
import numpy as np
from PIL import Image

root = Path(__file__).resolve().parent.parent
img_dir = Path(sys.argv[1] if len(sys.argv) > 1 else '/tmp/qimg/quran-images')

def frame(n):
    rgb = np.asarray(Image.open(img_dir / f'{n}.jpg').convert('RGB')).astype(int)
    H, W, _ = rgb.shape
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    gray = rgb.mean(2)
    rowp = (gray < 90)[:, int(W * 0.3):int(W * 0.7)].sum(1)
    sm = np.convolve(rowp, np.ones(9) / 9, 'same')
    best = None
    for d10 in range(760, 790):
        d = d10 / 10
        for y0 in range(110, 175):
            ys = (y0 + np.arange(15) * d).astype(int)
            sc = sm[ys].sum()
            if best is None or sc > best[0]: best = (sc, d, y0)
    _, d, y0 = best
    green = np.clip(g - np.maximum(r, b), 0, None) * (g < 210)
    col = green[300:1100].mean(0)
    hi = np.where(col > col.max() * 0.35)[0]
    groups = []
    for x in hi:
        if groups and x - groups[-1][1] <= 3: groups[-1][1] = x
        else: groups.append([int(x), int(x)])
    left = [gq for gq in groups if gq[1] < W // 2]
    right = [gq for gq in groups if gq[0] > W // 2]
    xl = left[-1][1] + 3 if left else 0
    xr = right[0][0] - 3 if right else W
    return xl, xr, float(y0), float(d)

if __name__ == '__main__':
    pages = []
    for n in range(1, 605):
        segs = json.load(open(root / 'data' / 'pages' / f'page_{n}.json'))
        if n <= 2:
            pages.append(dict(ok=0, xl=0, xr=0, y0=0, d=0, segs=[]))
            continue
        xl, xr, y0, d = frame(n)
        ok = 1 if (600 < xr - xl < 800 and 70 < d < 85) else 0
        out = []
        for e in segs:
            for s in e['segs']:
                line = round(s['y'] / 28.57)
                out.append((e['sura_id'], e['aya_id'], line, s['x'], s['x'] + s['w']))
        pages.append(dict(ok=ok, xl=xl, xr=xr, y0=y0, d=d, segs=out))
        if n % 50 == 0: print('page', n, xl, xr, round(y0, 1), d, 'ok' if ok else 'CHECK', flush=True)
    bad = [i + 1 for i, p in enumerate(pages) if not p['ok']]
    print('pages without layout:', bad)
    json.dump(pages, open(root / 'data' / 'layout.json', 'w'), default=float)
    # C header: per page frame + offset into segment table; segment = sura, ayah, line, x0, x1 (0..290)
    frames, offs, segs = [], [], []
    for p in pages:
        offs.append(len(segs))
        frames.append('{%d,%d,%d,%d,%d}' % (p['ok'], p['xl'], p['xr'], round(p['y0'] * 10), round(p['d'] * 100)))
        segs += ['{%d,%d,%d,%d,%d}' % s for s in p['segs']]
    offs.append(len(segs))
    h = ['/* Generated by tools/gen_layout.py - do not edit. */', '#pragma once',
         '/* {has_layout, text_left_px, text_right_px, first_line_center_px*10, line_pitch_px*100} on the 974x1403 image */',
         'static const short PAGE_FRAME[604][5] = {' + ','.join(frames) + '};',
         'static const unsigned short PAGE_SEG_OFF[605] = {' + ','.join(map(str, offs)) + '};',
         '/* {sura, ayah, line 0..14, x0, x1} in a 290-wide line, x from the left */',
         'static const unsigned short PAGE_SEGS[%d][5] = {' % len(segs) + ','.join(segs) + '};', '']
    (root / 'src' / 'quran_layout.h').write_text('\n'.join(h))
    print('segments', len(segs))
